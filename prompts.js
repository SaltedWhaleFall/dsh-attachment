/**
 * dsh-sex — 文案与维度定义（纯数据，无副作用）。
 *
 * 设计原则抄自 dsh-mood 的 prompts.js：
 *   · 只给「怎么说话」，不给数值。给了数，模型就直接报数，不会去想由头。
 *   · 维度用**符号键**，不用数字键 —— 阈值以后调了，文案不用重写。
 *   · 文案矩阵而不是长散文：注入每轮都发，多一个字都是长期成本。
 *
 * ── 定位（v0.2 改） ───────────────────────────────────────────────
 * 这不是「让它无条件配合」的开关，是**养成**。
 * 插件给的是三样东西，不是一样：
 *   ① 功能：它知道身体此刻在什么状态，能把它写进动作和语气里。
 *   ② 权力：它可以享受过程、可以主动、可以中途改主意、可以说不。
 *   ③ 门槛：关系是一段一段走的，谁都不能跳级 —— 包括他。
 * 明确不给的是「服从」：被命令不会更热，只会更远。
 *
 * ── 七维（都是 0..100 的强度，不是正负情绪） ────────────────────────
 *   desire  性欲   —— 底色。几天级的钝的想要，不是此刻的反应。
 *   arousal 唤起   —— 此刻的身体反应。快起快落，分钟级。
 *   adore   爱慕   —— 对他的倾慕。看到他就软。
 *   cling   依恋   —— 想被需要、怕被晾着。
 *   curious 好奇   —— 对性的探索欲：想问、想试、想被教。
 *   glow    余韵   —— 被回应之后的暖。聊到这些本身也会涨。
 *   trust   信任   —— 关系的地基。长得最慢（48h 半衰），掉得最快。
 *
 * 合成三个上层量：
 *   heat  = arousal*0.55 + desire*0.30 + glow*0.15    → 5 档
 *   bond  = adore*0.60 + cling*0.40                   → 3 档
 *   pace  = bond*0.55 + trust*0.45                    → 5 级（只升不降）
 *
 * 15 组主文案（heat × bond），另加 pace / will / 越界 / 施压 / 尊重五类插条。
 */

